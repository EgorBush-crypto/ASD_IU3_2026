package ru.bmstu.lab1.task_47;
import java.util.Scanner;
/**
 * Задача 47. Выводит матрицу, повёрнутую
 * на 90 градусов по часовой стрелке.
 * Исходная матрица остаётся без изменений.
 */
public class Main {
    /**
     * Считывает число строк, число столбцов и элементы матрицы.
     * Выводит каждый исходный столбец снизу вверх
     * как отдельную строку повёрнутой матрицы.
     *
     * @param args аргументы командной строки, не используются
     */
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        int rows = sc.nextInt(); // Считываение количества строк
        int col = sc.nextInt(); // Считывание количества столбцов
        int[][] a =  new int[rows][col]; // Создание двумерного массива
        for(int i=0; i<rows; i++){
            for(int j=0; j<col; j++){
                a[i][j] = sc.nextInt(); // Считывание элементов массива
            }
        }
        // Каждый столбец исходной матрицы становится строкой результата
        for(int i=0; i<col; i++){
            for(int j=0; j<rows; j++){
                // Читаем столбец снизу вверх, чтобы получить поворот вправо
                System.out.print(a[rows-1-j][i]+ " ");
            }
            // Переходим к следующей строке результата
            System.out.println();
        }
    }
}
